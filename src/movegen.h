void init_sliders_database();


inline uint64_t get_rook_attacks(int square, uint64_t total_occupancy, uint64_t not_friendly_pieces) {
    // Isolate blockers
    uint64_t blockers = total_occupancy & RookDatabase[square].mask;
    
    // Find index in attacks through magic
    uint64_t index = (blockers * RookDatabase[square].magic) >> RookDatabase[square].shift;
    
    // Find exact attack pattern using index and attack pointer
    return RookDatabase[square].attacks[index] & not_friendly_pieces;
}

inline uint64_t get_bishop_attacks(int square, uint64_t total_occupancy, uint64_t not_friendly_pieces) {
    uint64_t blockers = total_occupancy & BishopDatabase[square].mask;

    uint64_t index = (blockers * BishopDatabase[square].magic) >> BishopDatabase[square].shift;

    return BishopDatabase[square].attacks[index] & not_friendly_pieces;


}

inline uint64_t get_queen_attacks(int square, uint64_t total_occupancy, uint64_t not_friendly_pieces) {
    return get_rook_attacks(square, total_occupancy, not_friendly_pieces) | 
           get_bishop_attacks(square, total_occupancy, not_friendly_pieces);
}

inline uint64_t get_knight_attacks(int square, uint64_t not_friendly_pieces) {
    return KNIGHT_ATTACKS[square] & not_friendly_pieces;
}

inline uint64_t get_king_attacks(int square, uint64_t not_friendly_pieces) {
    return KING_ATTACKS[square] & not_friendly_pieces;
}

inline uint64_t get_pawn_attacks(int color, int square) {
    return PAWN_ATTACKS[color][square];
}
